uint32_t cp866_to_ucs(uint8_t ch)
{
    return ch < 0x80 ? ch : cp866_high[ch - 0x80];
}

int ucs_to_cp866(uint32_t ch)
{
    if (ch < 0x80)
        return (int)ch;
    for (size_t i = 0; i < sizeof(cp866_high) / sizeof(cp866_high[0]); ++i)
        if (cp866_high[i] == ch)
            return (int)i + 0x80;
    return -1;
}

uint8_t cp866_upper(uint8_t ch)
{
    if (ch >= 'a' && ch <= 'z')
        return (uint8_t)(ch - ('a' - 'A'));
    if (ch >= 0xa0 && ch <= 0xaf)
        return (uint8_t)(ch - 0x20);
    if (ch >= 0xe0 && ch <= 0xef)
        return (uint8_t)(ch - 0x50);
    if (ch >= 0xf1 && ch <= 0xf7 && (ch & 1))
        return (uint8_t)(ch - 1);
    return ch;
}
