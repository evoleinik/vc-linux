def text(table: dict, field: str, page: str) -> str:
    value = table.get(field)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{page}: {field} must be nonempty text")
    return value


def link_url(value: str) -> str:
    """Never turn an unsafe Markdown destination into executable HTML."""
    parsed = urlsplit(value)
    if (parsed.scheme and parsed.scheme != "https") or (parsed.netloc and parsed.scheme != "https"):
        raise ValueError(f"Link must be HTTPS or same-site: {value!r}")
    if parsed.scheme == "https" and not parsed.netloc:
        raise ValueError(f"HTTPS link has no host: {value!r}")
    if "\\" in value or any(ord(char) < 32 for char in value):
        raise ValueError(f"Unsafe link: {value!r}")
    return value


def inline_markup(value: str) -> str:
    """Escape all supplied text, recognizing only the brief's Markdown links."""
    chunks = []
    offset = 0
    for match in MARKDOWN_LINK.finditer(value):
        chunks.append(escape(value[offset:match.start()]))
        label, url = match.groups()
        chunks.append(f'<a href="{escape(link_url(url), quote=True)}">{escape(label)}</a>')
        offset = match.end()
    chunks.append(escape(value[offset:]))
    return "".join(chunks)


def paragraphs(value: str) -> str:
    return "\n".join(f"<p>{inline_markup(paragraph)}</p>"
                     for paragraph in re.split(r"\n\s*\n", value.strip()))


def program_path(program: dict, language: str) -> str:
    prefix = "/ru/" if language == "ru" else "/"
    return f"{prefix}{program['slug']}/"


def license_url(document: dict, program: dict) -> str:
    return f"{document['repo'].rstrip('/')}/blob/main/{program['license_path']}"


def run_programs(document: dict) -> dict[str, list[str]]:
    programs = {}
    for program in document["program"]:
        for entry in (program, *([program["also_run"]] if "also_run" in program else [])):
            slug = entry.get("slug")
            if not isinstance(slug, str) or not SLUG.fullmatch(slug):
                raise ValueError(f"{slug!r}: slug must be a lowercase URL segment")
            if slug in programs:
                raise ValueError(f"{slug}: duplicate run slug")
            lines = entry.get("run")
            if not isinstance(lines, list) or any(
                    not isinstance(line, str) or not 1 <= len(line) <= 126 or
                    any(not 32 <= ord(char) < 127 for char in line) for line in lines):
                raise ValueError(f"{slug}: run must contain printable DOS command lines of 1..126 bytes")
            programs[slug] = lines
    return programs


def validate(document: dict) -> None:
    for field in ("site", "repo", "doi"):
        value = text(document, field, "site")
        if not value.startswith("https://"):
            raise ValueError(f"site: {field} must be an absolute HTTPS URL")
        link_url(value)
    origin = urlsplit(document["site"])
    if origin.path not in ("", "/") or origin.query or origin.fragment:
        raise ValueError("site: site must be an origin, without a path, query or fragment")
    for language, expected in (("en", "/programs/"), ("ru", "/ru/")):
        hub = document["hub"][language]
        if hub.get("path") != expected:
            raise ValueError(f"hub.{language}: path must be {expected}")
        for field in ("title", "description", "h1", "body"):
            text(hub, field, f"hub.{language}")
    run_programs(document)
    for program in document["program"]:
        slug = program["slug"]
        if slug in ("programs", "ru"):
            raise ValueError(f"{slug}: slug overlaps a hub")
        for language in LANGUAGES:
            for field in ("title", "description", "h1", "body"):
                text(program.get(language, {}), field, f"{slug}.{language}")
        for field in ("name", "years", "license", "license_path", "source_url", "category", "linux"):
            text(program, field, slug)
        if program.get("schema_type") not in ("SoftwareApplication", "VideoGame"):
            raise ValueError(f"{slug}: unsupported schema_type")
        if not re.search(r"\d{4}", program["years"]):
            raise ValueError(f"{slug}: years must name a year")
        if not isinstance(program.get("authors"), list) or not program["authors"] or any(
                not isinstance(author, str) or not author for author in program["authors"]):
            raise ValueError(f"{slug}: authors must contain names")
        path = PurePosixPath(program["license_path"])
        if path.is_absolute() or ".." in path.parts or not (ROOT / path).is_file():
            raise ValueError(f"{slug}: license_path does not name a repository file")
        if not program["source_url"].startswith("https://"):
            raise ValueError(f"{slug}: source_url must use HTTPS")
        link_url(program["source_url"])
        if "also_run" in program:
            text(program["also_run"], "label", f"{slug}.also_run")


def program_schema(document: dict, program: dict, language: str) -> list[dict]:
    site = document["site"].rstrip("/")
    url = site + program_path(program, language)
    hub = document["hub"][language]
    application = {
        "@type": program["schema_type"], "name": program["name"],
        "author": [{"@type": "Organization" if name in ("Microsoft", "Columbia University") else "Person",
                    "name": name} for name in program["authors"]],
        **({"dateCreated": program["years"][:4]} if re.fullmatch(r"\d{4}(-\d{4})?", program["years"]) else {}),
        "license": license_url(document, program), "isBasedOn": program["source_url"],
        "applicationCategory": program["category"],
        "operatingSystem": "MS-DOS, run in a web browser as WebAssembly",
        "isAccessibleForFree": True, "inLanguage": language, "url": url,
    }
    crumbs = [("notanemulator", site + "/"), (hub["h1"], site + hub["path"]),
              (program[language]["h1"], url)]
    return [application, {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": index, "name": name, "item": item}
        for index, (name, item) in enumerate(crumbs, 1)]}]


def hub_schema(document: dict, language: str) -> list[dict]:
    site = document["site"].rstrip("/")
    hub = document["hub"][language]
    return [{"@type": "WebSite", "name": "notanemulator", "url": site + hub["path"],
             "description": hub["description"], "inLanguage": language},
            {"@type": "ItemList", "itemListElement": [
                {"@type": "ListItem", "position": index, "name": program["name"],
                 "url": site + program_path(program, language)}
                for index, program in enumerate(document["program"], 1)]}]


def page(document: dict, language: str, goatcounter: str, program: dict | None = None) -> str:
    site = document["site"].rstrip("/")
    hub = document["hub"][language]
    localized = program[language] if program else hub
    paths = {lang: program_path(program, lang) if program else document["hub"][lang]["path"]
             for lang in LANGUAGES}
    url = site + paths[language]
    other = "ru" if language == "en" else "en"
    title, description = escape(localized["title"]), escape(localized["description"], quote=True)
    alternates = "\n".join(
        f'  <link rel="alternate" hreflang="{lang}" href="{escape(site + path, quote=True)}">'
        for lang, path in (*paths.items(), ("x-default", paths["en"])))
    graph = program_schema(document, program, language) if program else hub_schema(document, language)
    # JSON escapes, rather than HTML entities, preserve JSON data and prevent
    # supplied strings containing </script> from ending the data block.
    structured = json.dumps({"@context": "https://schema.org", "@graph": graph}, ensure_ascii=False,
                            separators=(",", ":")).replace("<", "\\u003c")
    play = "/" if not program or program["slug"] == "volkov-commander" else f"/?run={program['slug']}"
    labels = document["labels"][language]
    buttons = f'<a class="play" href="{escape(play, quote=True)}">{escape(labels["play"])}</a>'
    if program and "also_run" in program:
        extra = program["also_run"]
        buttons += f'\n<a class="play" href="/?run={extra["slug"]}">{escape(extra["label"])}</a>'
    command = "$ <code>vc</code>"
    if program and program["linux"] != "vc":
        command += "\n&gt; <code>" + escape(program["linux"]) + "</code>"
    provenance = ""
    if program:
        provenance = (f'<p>{escape(labels["source"])}: '
                      f'<a href="{escape(program["source_url"], quote=True)}">GitHub</a> · '
                      f'<a href="{escape(license_url(document, program), quote=True)}">'
                      f'{escape(program["license"])}</a></p>')
    others = "\n".join(f'<li><a href="{program_path(item, language)}">{escape(item["name"])}</a></li>'
                       for item in document["program"] if item is not program)
    return f'''<!doctype html>
{GENERATED}<html lang="{language}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <base href="/">
  <title>{title}</title>
  <meta name="description" content="{description}">
  <link rel="canonical" href="{escape(url, quote=True)}">
{alternates}
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="notanemulator">
  <meta property="og:title" content="{title}">
  <meta property="og:description" content="{description}">
  <meta property="og:url" content="{escape(url, quote=True)}">
  <meta property="og:image" content="{escape(site, quote=True)}/social-preview.png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="{title}">
  <meta name="twitter:description" content="{description}">
  <meta name="twitter:image" content="{escape(site, quote=True)}/social-preview.png">
  <script type="application/ld+json">{structured}</script>
  <style>{CSS}</style>
</head>
<body>
<header>
  <nav><a href="/">notanemulator</a>
    <a href="{hub['path']}">{PROGRAM_LABELS[language]}</a>
    <a href="{paths[other]}" lang="{other}" hreflang="{other}">{LANGUAGE_NAMES[other]}</a></nav>
  <h1>{escape(localized['h1'])}</h1>
</header>
<main>
{paragraphs(localized['body'])}
<div class="play-buttons">{buttons}</div>
<h2>Linux</h2>
<pre>{command}</pre>
{provenance}
<h2>{PROGRAM_LABELS[language]}</h2>
<ul>
{others}
</ul>
</main>
<footer><a href="{escape(document['repo'], quote=True)}">GitHub</a> ·
  <a href="{escape(document['doi'], quote=True)}">Zenodo</a> ·
  <a href="{paths[other]}" lang="{other}" hreflang="{other}">{LANGUAGE_NAMES[other]}</a></footer>
{goatcounter}
</body>
</html>
'''


def sitemap(document: dict) -> str:
    site = document["site"].rstrip("/")
    pairs = [{lang: document["hub"][lang]["path"] for lang in LANGUAGES}]
    pairs.extend({lang: program_path(program, lang) for lang in LANGUAGES}
                 for program in document["program"])
    entries = [f"  <url><loc>{escape(site)}/</loc></url>"]
    for pair in pairs:
        links = "\n".join('    <xhtml:link rel="alternate" '
                          f'hreflang="{lang}" href="{escape(site + path, quote=True)}"/>'
                          for lang, path in (*pair.items(), ("x-default", pair["en"])))
        entries.extend(f"  <url>\n    <loc>{escape(site + path)}</loc>\n{links}\n  </url>"
                       for path in pair.values())
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" '
            'xmlns:xhtml="http://www.w3.org/1999/xhtml">\n' + "\n".join(entries) + "\n</urlset>\n")


def llms(document: dict) -> str:
    site = document["site"].rstrip("/")
    hub = document["hub"]["en"]
    summary = " ".join(re.split(r"\n\s*\n", hub["body"].strip())[0].split())
    programs = "\n".join(f"- [{item['name']}]({site}{program_path(item, 'en')}): {item['en']['description']}"
                         for item in document["program"])
    return (f"# notanemulator\n\n> {summary}\n\n## Programs\n\n{programs}\n\n## Source\n\n"
            f"- [GitHub]({document['repo']})\n- [Zenodo]({document['doi']})\n"
            f"- [notanemulator]({site}/)\n- [{hub['title']}]({site}{hub['path']})\n")


def render(document: dict, goatcounter: str) -> dict[str, bytes]:
    validate(document)
    files = {}
    for language in LANGUAGES:
        hub_path = document["hub"][language]["path"]
        files[hub_path.lstrip("/") + "index.html"] = page(document, language, goatcounter).encode("utf-8")
        for program in document["program"]:
            path = program_path(program, language).lstrip("/") + "index.html"
            files[path] = page(document, language, goatcounter, program).encode("utf-8")
    files["sitemap.xml"] = sitemap(document).encode("utf-8")
    files["llms.txt"] = llms(document).encode("utf-8")
    files["robots.txt"] = (f"User-agent: *\nAllow: /\n\nSitemap: {document['site'].rstrip('/')}/sitemap.xml\n").encode("utf-8")
    files["vc-programs.js"] = programs_module(document).encode("utf-8")
    return files


def programs_module(document: dict) -> str:
    entries = ",\n".join(f"  {json.dumps(slug)}: Object.freeze({json.dumps(lines)})"
                         for slug, lines in run_programs(document).items())
    return ("// Generated by tools/site_pages.py; do not edit.\n"
            f"export const programs = Object.freeze({{\n{entries}\n}});\n")


def check_output(path: Path) -> None:
    if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
        raise ValueError(f"Refusing to replace symlink: {path}")
    if path.exists() and not path.is_file():
        raise ValueError(f"Refusing to replace non-regular file: {path}")


def publish(config: Path, destination: Path) -> int:
    with config.open("rb") as stream:
        document = tomllib.load(stream)
    home = destination / "index.html"
    if not home.is_file():
        home = ROOT / "web/index.html"
    counters = GOATCOUNTER.findall(home.read_text(encoding="utf-8"))
    if len(counters) != 1:
        raise ValueError(f"{home}: expected exactly one GoatCounter tag")
    files = render(document, counters[0])
    preview = (ROOT / "docs/social-preview.png").read_bytes()
    if (preview[:16] != b"\x89PNG\r\n\x1a\n\0\0\0\rIHDR" or
            (int.from_bytes(preview[16:20], "big"), int.from_bytes(preview[20:24], "big")) != (1200, 630)):
        raise ValueError("docs/social-preview.png: expected a 1200x630 PNG")
    files["social-preview.png"] = preview
    # Validate every input before changing published pages. Only files carrying
    # our exact marker are retired on incremental builds, outside the website.
    stale = []
    for path in sorted(destination.rglob("index.html")):
        if path.relative_to(destination).as_posix() in files or path == destination / "index.html":
            continue
        if path.is_symlink() or not path.is_file():
            continue
        data = path.read_bytes()
        if data.startswith(("<!doctype html>\n" + GENERATED).encode("utf-8")):
            relative = path.relative_to(destination)
            retired = destination.parent / (destination.name + "-retired-pages") / relative.parent
            retired /= f"{relative.name}.{sha256(data).hexdigest()}"
            check_output(retired)
            if retired.exists() and retired.read_bytes() != data:
                raise ValueError(f"Refusing to overwrite different retired page: {retired}")
            stale.append((path, data, retired))
    for name in files:
        check_output(destination / name)
    for name, contents in files.items():
        update(destination / name, contents)
    for path, data, retired in stale:
        update(retired, data)
        path.unlink()  # A recoverable copy has been published outside the site.
        print(f"site pages: retired {path} to {retired}")
    return sum(name.endswith(".html") for name in files)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "site/pages.toml")
    parser.add_argument("--output", type=Path, default=ROOT / "build/web")
    parser.add_argument("--print-programs", action="store_true",
                        help="print only the Play map, which is all the app's version stamp depends on")
    arguments = parser.parse_args()
    if arguments.print_programs:
        with arguments.config.open("rb") as stream:
            document = tomllib.load(stream)
        validate(document)
        sys.stdout.write(programs_module(document))
        return
    count = publish(arguments.config, arguments.output)
    print(f"site pages: published {count} bilingual pages, search metadata and the lazy Play map")


if __name__ == "__main__":
    main()
