"""Render the supplied bilingual page text and search metadata for the web build.

Usage: .venv/bin/python tools/site_pages.py [--config site/pages.toml] [--output build/web]
Run after publishing index.html so every page uses its exact GoatCounter tag.
The renderer deliberately does not translate or repair the supplied prose;
tests/test_site.mjs independently checks its editorial and deployment gates.
"""
