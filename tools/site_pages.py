GENERATED = "<!-- Generated by tools/site_pages.py; do not edit. -->\n"
LANGUAGES = ("en", "ru")
LANGUAGE_NAMES = {"en": "English", "ru": "Русский"}
PROGRAM_LABELS = {"en": "Programs", "ru": "Программы"}
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
MARKDOWN_LINK = re.compile(r"\[([^\]\n]+)\]\(([^\s)]+)\)")
GOATCOUNTER = re.compile(r"<script\b[^>]*\bdata-goatcounter=[\"'][^\"']+[\"'][^>]*>\s*</script>")
